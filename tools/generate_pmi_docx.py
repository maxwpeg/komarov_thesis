def normalize_spaces(text: str) -> str:
    return " ".join((text or "").split())


def set_run_font(run, *, size: float = 14, bold: bool | None = None, italic: bool | None = None):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    if italic is not None:
        run.italic = italic


def set_paragraph_style(paragraph, style_name: str):
    try:
        paragraph.style = style_name
    except KeyError:
        paragraph.style = "Normal"


def format_paragraph(
    paragraph,
    *,
    style_name: str,
    align: WD_ALIGN_PARAGRAPH = WD_ALIGN_PARAGRAPH.JUSTIFY,
    first_line_indent_cm: float | None = 1.25,
    space_before_pt: float = 0,
    space_after_pt: float = 0,
    line_spacing: float = 1.5,
):
    set_paragraph_style(paragraph, style_name)
    paragraph.alignment = align
    paragraph.paragraph_format.line_spacing = line_spacing
    paragraph.paragraph_format.space_before = Pt(space_before_pt)
    paragraph.paragraph_format.space_after = Pt(space_after_pt)
    if first_line_indent_cm is None:
        paragraph.paragraph_format.first_line_indent = None
    else:
        paragraph.paragraph_format.first_line_indent = Cm(first_line_indent_cm)


def clear_paragraph(paragraph):
    for run in list(paragraph.runs):
        paragraph._p.remove(run._r)


def replace_paragraph_text(
    paragraph,
    text: str,
    *,
    style_name: str,
    bold: bool = False,
    italic: bool = False,
    align: WD_ALIGN_PARAGRAPH = WD_ALIGN_PARAGRAPH.LEFT,
    first_line_indent_cm: float | None = None,
    space_before_pt: float = 6,
    space_after_pt: float = 6,
    line_spacing: float = 1.5,
):
    clear_paragraph(paragraph)
    format_paragraph(
        paragraph,
        style_name=style_name,
        align=align,
        first_line_indent_cm=first_line_indent_cm,
        space_before_pt=space_before_pt,
        space_after_pt=space_after_pt,
        line_spacing=line_spacing,
    )
    run = paragraph.add_run(text)
    set_run_font(run, bold=bold, italic=italic)


def insert_paragraph_before(
    anchor,
    text: str = "",
    *,
    style_name: str = "Body Text",
    bold: bool = False,
    italic: bool = False,
    align: WD_ALIGN_PARAGRAPH = WD_ALIGN_PARAGRAPH.JUSTIFY,
    first_line_indent_cm: float | None = 1.25,
    space_before_pt: float = 0,
    space_after_pt: float = 0,
    line_spacing: float = 1.5,
):
    paragraph = anchor.insert_paragraph_before()
    format_paragraph(
        paragraph,
        style_name=style_name,
        align=align,
        first_line_indent_cm=first_line_indent_cm,
        space_before_pt=space_before_pt,
        space_after_pt=space_after_pt,
        line_spacing=line_spacing,
    )
    if text:
        run = paragraph.add_run(text)
        set_run_font(run, bold=bold, italic=italic)
    return paragraph


def delete_paragraph(paragraph):
    element = paragraph._element
    parent = element.getparent()
    if parent is not None:
        parent.remove(element)


def find_paragraph_index(doc: Document, predicate, *, start: int = 0) -> int:
    for index in range(start, len(doc.paragraphs)):
        if predicate(doc.paragraphs[index]):
            return index
    raise ValueError("Не удалось найти требуемый абзац в документе.")


def add_case(anchor, case_data: dict[str, object]):
    insert_paragraph_before(
        anchor,
        case_data["title"],
        style_name="Body Text",
        bold=True,
        align=WD_ALIGN_PARAGRAPH.LEFT,
        first_line_indent_cm=None,
        space_before_pt=6,
        space_after_pt=0,
    )
    insert_paragraph_before(anchor, f"Назначение испытания. {case_data['purpose']}")
    insert_paragraph_before(anchor, f"Предусловия. {case_data['preconditions']}")
    insert_paragraph_before(
        anchor,
        "Порядок выполнения испытания:",
        style_name="Body Text",
        bold=True,
        align=WD_ALIGN_PARAGRAPH.LEFT,
        first_line_indent_cm=None,
    )
    for step_number, step in enumerate(case_data["steps"], start=1):
        insert_paragraph_before(anchor, f"{step_number}. {step}")
    insert_paragraph_before(
        anchor,
        "Ожидаемый результат:",
        style_name="Body Text",
        bold=True,
        align=WD_ALIGN_PARAGRAPH.LEFT,
        first_line_indent_cm=None,
    )
    for result_number, result in enumerate(case_data["expected"], start=1):
        insert_paragraph_before(anchor, f"{result_number}. {result}")


def build_document():
    if not SOURCE_PATH.exists():
        raise FileNotFoundError(f"Не найден исходный документ: {SOURCE_PATH}")

    doc = Document(str(SOURCE_PATH))

    methods_index = find_paragraph_index(doc, lambda p: normalize_spaces(p.text) == "МЕТОДЫ ИСПЫТАНИЙ")
    documentation_index = find_paragraph_index(
        doc,
        lambda p: normalize_spaces(p.text) == "Проверка требований к технической документации",
        start=methods_index,
    )
    functional_start_index = find_paragraph_index(
        doc,
        lambda p: normalize_spaces(p.text) == "Проверка требований к функциональным характеристикам",
        start=methods_index,
    )
    interface_primary_index = find_paragraph_index(
        doc,
        lambda p: normalize_spaces(p.text) == "Проверка требований к интерфейсу",
        start=documentation_index,
    )
    registration_index = find_paragraph_index(
        doc,
        lambda p: normalize_spaces(p.text) == "ЛИСТ РЕГИСТРАЦИИ ИЗМЕНЕНИЙ",
        start=functional_start_index,
    )

    replace_paragraph_text(
        doc.paragraphs[documentation_index],
        "Проверка требований к программной документации",
        style_name="Heading 2",
        bold=True,
        align=WD_ALIGN_PARAGRAPH.LEFT,
        first_line_indent_cm=None,
    )
    replace_paragraph_text(
        doc.paragraphs[interface_primary_index],
        "Проверка требований к интерфейсу",
        style_name="Heading 2",
        bold=True,
        align=WD_ALIGN_PARAGRAPH.LEFT,
        first_line_indent_cm=None,
    )

    for paragraph in list(doc.paragraphs[functional_start_index:registration_index]):
        delete_paragraph(paragraph)

    registration_anchor = next(
        paragraph
        for paragraph in doc.paragraphs
        if normalize_spaces(paragraph.text) == "ЛИСТ РЕГИСТРАЦИИ ИЗМЕНЕНИЙ"
    )

    insert_paragraph_before(
        registration_anchor,
        "Проверка требований к функциональным характеристикам",
        style_name="Heading 2",
        bold=True,
        align=WD_ALIGN_PARAGRAPH.LEFT,
        first_line_indent_cm=None,
        space_before_pt=6,
        space_after_pt=6,
    )
    insert_paragraph_before(
        registration_anchor,
        (
            "Проверка требований к функциональным характеристикам выполняется последовательным прохождением "
            "контрольных сценариев, охватывающих основные пользовательские и служебные функции системы. "
            "Каждое испытание считается успешно пройденным, если фактический результат полностью совпадает "
            "с ожидаемым результатом, а сведения о состоянии проекта, плана, оборудования, файлов и "
            "обучающих примеров сохраняются корректно."
        ),
    )
    insert_paragraph_before(
        registration_anchor,
        (
            "При выполнении испытаний допускается использовать как пользовательский интерфейс, так и "
            "контроль состояния через штатный API и содержимое базы данных, если это необходимо для "
            "подтверждения факта сохранения изменений."
        ),
    )

    for case_data in FUNCTIONAL_TESTS:
        add_case(registration_anchor, case_data)

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(OUTPUT_PATH))


if __name__ == "__main__":
    build_document()
