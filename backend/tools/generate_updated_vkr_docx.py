def find_paragraph(doc: Document, text: str):
    for paragraph in doc.paragraphs:
        if paragraph.text.strip() == text:
            return paragraph
    raise ValueError(f"Paragraph not found: {text}")


def remove_body_range(doc: Document, start_paragraph, end_paragraph) -> None:
    body = doc.element.body
    children = list(body)
    start_index = children.index(start_paragraph._element)
    end_index = children.index(end_paragraph._element)
    for element in children[start_index:end_index]:
        body.remove(element)


def insert_content(doc: Document, before_paragraph, items: Iterable[DocItem], figures: dict[str, Path]) -> None:
    styles = {style.name for style in doc.styles}
    for item in items:
        paragraph = before_paragraph.insert_paragraph_before()
        if item.kind == "image":
            paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = paragraph.add_run()
            run.add_picture(str(figures[item.image]), width=Cm(item.width_cm))
            continue

        paragraph.style = item.style if item.style in styles else "Normal"
        if item.kind == "caption":
            paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
        paragraph.add_run(item.text)


def assert_unchanged_prefix(original: Document, updated: Document) -> None:
    original_start = next(i for i, p in enumerate(original.paragraphs) if p.text.strip() == CHAPTER_2_TITLE)
    updated_start = next(i for i, p in enumerate(updated.paragraphs) if p.text.strip() == CHAPTER_2_TITLE)
    original_prefix = [p.text for p in original.paragraphs[:original_start]]
    updated_prefix = [p.text for p in updated.paragraphs[:updated_start]]
    if original_prefix != updated_prefix:
        raise AssertionError("Text before chapter 2 changed")


def main() -> None:
    if not SOURCE_DOCX.exists():
        raise FileNotFoundError(SOURCE_DOCX)

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    figures = create_figures()

    working_copy = OUTPUT_DIR / "source_copy.docx"
    shutil.copy2(SOURCE_DOCX, working_copy)

    doc = Document(working_copy)
    chapter_2 = find_paragraph(doc, CHAPTER_2_TITLE)
    conclusion = find_paragraph(doc, CONCLUSION_TITLE)
    remove_body_range(doc, chapter_2, conclusion)
    insert_content(doc, conclusion, build_content(), figures)
    doc.save(OUTPUT_DOCX)
    working_copy.unlink(missing_ok=True)

    original = Document(SOURCE_DOCX)
    updated = Document(OUTPUT_DOCX)
    assert_unchanged_prefix(original, updated)

    print(OUTPUT_DOCX)
    print(f"figures={len(figures)} paragraphs={len(updated.paragraphs)} inline_shapes={len(updated.inline_shapes)}")


if __name__ == "__main__":
    main()
