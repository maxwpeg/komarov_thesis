def _wrap_text(draw: ImageDraw.ImageDraw, text: str, font: ImageFont.ImageFont, max_width: int) -> list[str]:
    lines: list[str] = []
    for raw_line in text.splitlines():
        words = raw_line.split()
        current = ""
        for word in words:
            candidate = f"{current} {word}".strip()
            if draw.textbbox((0, 0), candidate, font=font)[2] <= max_width:
                current = candidate
            else:
                if current:
                    lines.append(current)
                current = word
        if current:
            lines.append(current)
    return lines or [""]


def _centered_multiline(
    draw: ImageDraw.ImageDraw,
    box: tuple[int, int, int, int],
    text: str,
    font: ImageFont.ImageFont,
    fill: str = "#172033",
) -> None:
    x1, y1, x2, y2 = box
    lines = _wrap_text(draw, text, font, max(40, x2 - x1 - 28))
    line_heights = [draw.textbbox((0, 0), line, font=font)[3] + 4 for line in lines]
    total_h = sum(line_heights)
    y = y1 + (y2 - y1 - total_h) // 2
    for line, height in zip(lines, line_heights):
        bbox = draw.textbbox((0, 0), line, font=font)
        x = x1 + (x2 - x1 - (bbox[2] - bbox[0])) // 2
        draw.text((x, y), line, font=font, fill=fill)
        y += height


def _box(
    draw: ImageDraw.ImageDraw,
    xy: tuple[int, int, int, int],
    text: str,
    fill: str = "#f7fbff",
    outline: str = "#2f5f8f",
    font: ImageFont.ImageFont = FONT_BOX,
    radius: int = 18,
) -> None:
    draw.rounded_rectangle(xy, radius=radius, fill=fill, outline=outline, width=3)
    _centered_multiline(draw, xy, text, font)


